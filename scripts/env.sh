#!/usr/bin/env bash
#------------------------------------------------------------------------------
# env.sh - run-time environment. Each DD_<name> variable plays the role of a
# JCL DD statement: COBOL programs ASSIGN TO "<name>" and GnuCOBOL maps that
# name to the file in DD_<name>.
#
# Domain-specific DDs live in scripts/env.d/*.sh and are sourced below.
#------------------------------------------------------------------------------
export CB_ROOT="${CB_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
# CB_WORK holds the run-time datasets (master/ and output/). Seed and input
# files are always read from the repository. Point CB_WORK elsewhere to keep
# an isolated copy of the bank (e.g. CB_WORK=/tmp/cbs-test scripts/init-data.sh)
export CB_WORK="${CB_WORK:-$CB_ROOT/data}"
export COB_LIBRARY_PATH="$CB_ROOT/build/lib"
export PATH="$CB_ROOT/build/bin:$PATH"

M="$CB_WORK/master"; O="$CB_WORK/output"
I="$CB_ROOT/data/input"; S="$CB_ROOT/data/seed"

# --- control ----------------------------------------------------------------
export DD_BANKCTL="$M/bankctl.dat"

# --- masters (indexed) --------------------------------------------------------
export DD_CUSTMST="$M/custmst.idx"
export DD_ACCTMST="$M/acctmst.idx"
export DD_PRODMST="$M/prodmst.idx"
export DD_HOLDMST="$M/holdmst.idx"

# --- seed inputs (pipe-delimited) --------------------------------------------
export DD_CUSTSEED="$S/customers.psv"
export DD_PRODSEED="$S/products.psv"
export DD_ACCTSEED="$S/accounts.psv"
export DD_TRANSEED="$M/daytran.psv"          # built by init-data.sh
export DD_HISTSEED="$M/tranhist.psv"         # built by init-data.sh

# --- daily transaction flow (sequential, TRANREC) ------------------------------
export DD_TRANIN="$M/tranin.dat"             # channel transactions (from seed)
export DD_ACHTRAN="$O/achtran.dat"           # transactions generated by ACHIN
export DD_PAYTRAN="$O/paytran.dat"           # transactions generated by PAYPROC
export DD_TRANEDT="$O/tranedt.dat"           # edited, ready to post
export DD_TRANREJ="$O/tranrej.dat"           # rejected by edit / posting
export DD_TRANPOST="$O/tranpost.dat"         # everything posted today
export DD_TRANHIST="$M/tranhist.dat"         # cumulative history

# --- cross-domain outputs -----------------------------------------------------
export DD_ALERTS="$O/alerts.dat"

for f in "$CB_ROOT"/scripts/env.d/*.sh; do
  if [ -f "$f" ]; then . "$f"; fi
done
